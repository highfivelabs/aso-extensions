#!/usr/bin/env bash
# Copyright 2026 High Five Labs
# SPDX-License-Identifier: MIT
# Generate deepcopy and CRDs from apis/ the way Azure Service Operator's
# Taskfile does for its own (controller:generate-crds): controller-gen
# v0.19.0, object and crd with crdVersions=v1,allowDangerousTypes=true.
# Output: apis/**/zz_generated.deepcopy.go, config/crds/*.yaml.
#
# Also, for tests only: the CRDs of the ASO kinds our kinds name as owners
# (dbforpostgresql.azure.com FlexibleServer, keyvault.azure.com Vault,
# resources.azure.com ResourceGroup for ManagementLock, sql.azure.com
# Server and ServersDatabase for the Azure SQL User),
# generated from ASO's own types at the pin into config/test/aso-crds/.
# They stand in for ASO's install in envtest and on kind; ASO's real CRDs
# carry more versions and a conversion webhook.

set -o errexit
set -o nounset
set -o pipefail

# File name order (the kustomization's lists) must not depend on the machine's locale.
export LC_ALL=C

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"

CONTROLLER_GEN="go run sigs.k8s.io/controller-tools/cmd/controller-gen@v0.19.0"
ASO="third_party/azure-service-operator/v2"

rm -rf config/crds
${CONTROLLER_GEN} \
  object:headerFile=hack/boilerplate.go.txt \
  paths="./apis/..."
# CRDs: the hand-written kinds, and the API version of each generated ARM kind
# (apis/arm/<group>/<version>). Its storage version and ARM wire types
# (.../storage, .../arm) are in-memory types: a CRD with one version needs no
# conversion webhook (hack/generate-arm.sh, ASO_GENERATOR_API_STORAGE).
crd_paths=()
for pkg in $(go list ./apis/... | grep -v -e '/storage$' -e '/arm$'); do
  crd_paths+=("paths=${pkg}")
done
${CONTROLLER_GEN} \
  crd:crdVersions=v1,allowDangerousTypes=true \
  output:crd:artifacts:config=config/crds/ \
  "${crd_paths[@]}"

{
  echo "# Generated by hack/generate.sh. Do not edit."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources:"
  for f in config/crds/*.yaml; do
    [[ "$(basename "${f}")" == kustomization.yaml ]] && continue
    echo "- $(basename "${f}")"
  done
} > config/crds/kustomization.yaml

# Test-only owner CRDs, from ASO's types at the pin (storage versions only).
out="$(mktemp -d)"
trap 'rm -rf "${out}"' EXIT
(
  cd "${ASO}"
  ${CONTROLLER_GEN} crd:crdVersions=v1,allowDangerousTypes=true \
    output:crd:artifacts:config="${out}" \
    paths="./api/dbforpostgresql/v20250801/storage/..." \
    paths="./api/keyvault/v1api20230701/storage/..." \
    paths="./api/resources/v1api20200601/storage/..." \
    paths="./api/app/v20250101/storage/..." \
    paths="./api/web/v20260715/storage/..." \
    paths="./api/operationalinsights/v20250701/storage/..." \
    paths="./api/containerregistry/v20251101/storage/..." \
    paths="./api/compute/v20220301/storage/..." \
    paths="./api/sql/v20250101/storage/..." \
    paths="./api/containerservice/v20260501/storage/..." \
    paths="./api/containerservice/v1api20250301/storage/..." \
    paths="./api/network/v1api20180501/storage/..." \
    paths="./api/network/v1api20240601/storage/..." \
    paths="./api/documentdb/v1api20240815/storage/..." \
    paths="./api/cognitiveservices/v20250601/storage/..." \
    paths="./api/storage/v20260601/storage/..."
)
rm -rf config/test/aso-crds
mkdir -p config/test/aso-crds
cp "${out}/dbforpostgresql.azure.com_flexibleservers.yaml" "${out}/keyvault.azure.com_vaults.yaml" \
  "${out}/resources.azure.com_resourcegroups.yaml" "${out}/app.azure.com_managedenvironments.yaml" "${out}/app.azure.com_containerapps.yaml" \
  "${out}/web.azure.com_sites.yaml" "${out}/operationalinsights.azure.com_workspaces.yaml" \
  "${out}/containerregistry.azure.com_registries.yaml" "${out}/compute.azure.com_virtualmachines.yaml" \
  "${out}/sql.azure.com_servers.yaml" "${out}/sql.azure.com_serversdatabases.yaml" \
  "${out}/containerservice.azure.com_managedclusters.yaml" "${out}/containerservice.azure.com_fleets.yaml" \
  "${out}/network.azure.com_dnszones.yaml" "${out}/network.azure.com_privatednszones.yaml" \
  "${out}/documentdb.azure.com_databaseaccounts.yaml" "${out}/documentdb.azure.com_sqldatabases.yaml" \
  "${out}/cognitiveservices.azure.com_accounts.yaml" "${out}/cognitiveservices.azure.com_projects.yaml" \
  "${out}/storage.azure.com_storageaccounts.yaml" config/test/aso-crds/
{
  echo "# Generated by hack/generate.sh from Azure Service Operator's types at the pin. Tests only."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources:"
  echo "- dbforpostgresql.azure.com_flexibleservers.yaml"
  echo "- keyvault.azure.com_vaults.yaml"
  echo "- resources.azure.com_resourcegroups.yaml"
  echo "- app.azure.com_managedenvironments.yaml"
  echo "- app.azure.com_containerapps.yaml"
  echo "- web.azure.com_sites.yaml"
  echo "- operationalinsights.azure.com_workspaces.yaml"
  echo "- containerregistry.azure.com_registries.yaml"
  echo "- compute.azure.com_virtualmachines.yaml"
  echo "- sql.azure.com_servers.yaml"
  echo "- sql.azure.com_serversdatabases.yaml"
  echo "- containerservice.azure.com_managedclusters.yaml"
  echo "- containerservice.azure.com_fleets.yaml"
  echo "- network.azure.com_dnszones.yaml"
  echo "- network.azure.com_privatednszones.yaml"
  echo "- documentdb.azure.com_databaseaccounts.yaml"
  echo "- documentdb.azure.com_sqldatabases.yaml"
  echo "- cognitiveservices.azure.com_accounts.yaml"
  echo "- cognitiveservices.azure.com_projects.yaml"
  echo "- storage.azure.com_storageaccounts.yaml"
} > config/test/aso-crds/kustomization.yaml

# The manager's rights over the generated ARM kinds: one group per
# apis/arm/<group> directory.
{
  echo "# Generated by hack/generate.sh from apis/arm. Do not edit."
  echo "# The manager's rights over the ARM kinds ASO's generator wrote."
  echo "apiVersion: rbac.authorization.k8s.io/v1"
  echo "kind: ClusterRole"
  echo "metadata:"
  echo "  name: arm-kinds"
  echo "rules:"
  echo "- apiGroups:"
  for d in apis/arm/*/; do echo "  - $(basename "${d}").azure.hfl.dev"; done
  echo "  resources: [\"*\"]"
  echo "  verbs: [\"get\", \"list\", \"watch\", \"create\", \"update\", \"patch\", \"delete\"]"
  echo "- apiGroups:"
  for d in apis/arm/*/; do echo "  - $(basename "${d}").azure.hfl.dev"; done
  echo "  resources: [\"*/status\", \"*/finalizers\"]"
  echo "  verbs: [\"get\", \"update\", \"patch\"]"
  echo "---"
  echo "apiVersion: rbac.authorization.k8s.io/v1"
  echo "kind: ClusterRoleBinding"
  echo "metadata:"
  echo "  name: arm-kinds"
  echo "roleRef:"
  echo "  apiGroup: rbac.authorization.k8s.io"
  echo "  kind: ClusterRole"
  echo "  name: arm-kinds"
  echo "subjects:"
  echo "- kind: ServiceAccount"
  echo "  name: manager"
  echo "  namespace: azureserviceoperator-system"
} > config/rbac/arm-kinds.yaml

# The manager's read-only access to ASO's resources: a ManagementLock's
# owner may be any ASO kind, read by name (get only; no list or watch) for
# its ARM ID and Ready condition. One rule per ASO API group at the pin,
# from the groups ASO's API packages declare; entra.azure.com is left out,
# its objects have no ARM ID.
{
  echo "# Generated by hack/generate.sh from Azure Service Operator's API groups at the pin. Do not edit."
  echo "# A ManagementLock's owner may be any ASO resource: the manager reads it by"
  echo "# name (get only) for its ARM ID and Ready condition."
  echo "apiVersion: rbac.authorization.k8s.io/v1"
  echo "kind: ClusterRole"
  echo "metadata:"
  echo "  name: aso-owner-reader"
  echo "rules:"
  echo "- apiGroups:"
  grep -rh "^// +groupName=" "${ASO}"/api/*/*/doc.go | sed 's|^// +groupName=||' | LC_ALL=C sort -u | grep -v '^entra\.azure\.com$' | sed 's|^|  - |'
  echo "  resources: [\"*\"]"
  echo "  verbs: [\"get\"]"
  echo "---"
  echo "apiVersion: rbac.authorization.k8s.io/v1"
  echo "kind: ClusterRoleBinding"
  echo "metadata:"
  echo "  name: aso-owner-reader"
  echo "roleRef:"
  echo "  apiGroup: rbac.authorization.k8s.io"
  echo "  kind: ClusterRole"
  echo "  name: aso-owner-reader"
  echo "subjects:"
  echo "- kind: ServiceAccount"
  echo "  name: manager"
  echo "  namespace: azureserviceoperator-system"
} > config/rbac/aso-owner-reader.yaml
