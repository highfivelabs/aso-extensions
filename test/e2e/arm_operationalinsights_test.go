// logAnalytics makes the ASO footprint the children of a Log Analytics
// workspace hang from: a resource group and a Workspace ASO has provisioned
// (stand-ins), and the same two in the fake Resource Manager. It returns the
// workspace's ARM ID and the resource group's.
func logAnalytics(t *testing.T, ns string) (workspaceID, rgID string) {
	t.Helper()
	rgID = "/subscriptions/" + subID + "/resourceGroups/" + ns + "-rg"
	workspaceID = rgID + "/providers/Microsoft.OperationalInsights/workspaces/" + ns + "-law"
	armFake.AddResource(rgID)
	armFake.AddResource(workspaceID)
	resourceGroup(t, ns, "rg", ns+"-rg")
	logAnalyticsWorkspace(t, ns, "law", "rg", ns+"-rg", ns+"-law")
	return workspaceID, rgID
}

// A table of ASO's Workspace (custom log, retention, schema), a saved search,
// a linked storage account, a linked service and a data export, generated by ASO's
// generator from the Microsoft.OperationalInsights spec: PUT with the
// namespace's identity, changed, and deleted.
func TestWorkspaceChildren(t *testing.T) {
	ctx := context.Background()
	ns := namespace(t, "law")
	strictCredential(t, ns, clientA)
	trustNamespace(ns)
	workspaceID, rgID := logAnalytics(t, ns)
	storageID := rgID + "/providers/Microsoft.Storage/storageAccounts/lawlogs"
	automationID := rgID + "/providers/Microsoft.Automation/automationAccounts/auto"
	armFake.AddResource(storageID)
	armFake.AddResource(automationID)

	table := &oi.WorkspacesTable{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: "appevents"},
		Spec: oi.WorkspacesTable_Spec{
			AzureName:            "AppEvents_CL",
			Owner:                &genruntime.KnownResourceReference{Name: "law"},
			Plan:                 ptr(oi.TablePlanEnum_Analytics),
			RetentionInDays:      ptr(30),
			TotalRetentionInDays: ptr(180),
			Schema: &oi.Schema{
				Name: ptr("AppEvents_CL"),
				Columns: []oi.Column{
					{Name: ptr("TimeGenerated"), Type: ptr(oi.ColumnTypeEnum_DateTime)},
					{Name: ptr("Message"), Type: ptr(oi.ColumnTypeEnum_String)},
				},
			},
		},
	}
	search := &oi.WorkspacesSavedSearch{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: "errors"},
		Spec: oi.WorkspacesSavedSearch_Spec{
			AzureName:   "app-errors",
			Owner:       &genruntime.KnownResourceReference{Name: "law"},
			Category:    ptr("Application"),
			DisplayName: ptr("Application errors"),
			Query:       ptr("AppEvents_CL | where Message contains 'error'"),
			Version:     ptr(2),
			Tags:        []oi.Tag{{Name: ptr("team"), Value: ptr("platform")}},
		},
	}
	storage := &oi.WorkspacesLinkedStorageAccount{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: "customlogs"},
		Spec: oi.WorkspacesLinkedStorageAccount_Spec{
			AzureName:                "CustomLogs",
			Owner:                    &genruntime.KnownResourceReference{Name: "law"},
			StorageAccountReferences: []genruntime.ResourceReference{{ARMID: storageID}},
		},
	}
	linked := &oi.WorkspacesLinkedService{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: "automation"},
		Spec: oi.WorkspacesLinkedService_Spec{
			AzureName:         "Automation",
			Owner:             &genruntime.KnownResourceReference{Name: "law"},
			ResourceReference: &genruntime.ResourceReference{ARMID: automationID},
		},
	}
	export := &oi.WorkspacesDataExport{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: "archive"},
		Spec: oi.WorkspacesDataExport_Spec{
			AzureName:   "archive",
			Owner:       &genruntime.KnownResourceReference{Name: "law"},
			TableNames:  []string{"Heartbeat", "AppEvents_CL"},
			Enable:      ptr(true),
			Destination: &oi.Destination{ResourceReference: &genruntime.ResourceReference{ARMID: storageID}},
		},
	}
	all := []client.Object{table, search, storage, linked, export}
	for _, o := range all {
		if err := k8s.Create(ctx, o); err != nil {
			t.Fatal(err)
		}
	}
	for _, o := range all {
		eventually(t, timeout, fmt.Sprintf("%T Ready", o), ready(o.(conditioned)))
	}

	tableID := workspaceID + "/tables/AppEvents_CL"
	expectResource(t, tableID, func(r map[string]any) error {
		p := properties(r)
		schema, _ := p["schema"].(map[string]any)
		cols, _ := schema["columns"].([]any)
		if r["type"] != "Microsoft.OperationalInsights/workspaces/tables" || p["plan"] != "Analytics" ||
			p["retentionInDays"] != float64(30) || p["totalRetentionInDays"] != float64(180) || len(cols) != 2 {
			return fmt.Errorf("resource: %v", r)
		}
		return nil
	})
	expectResource(t, workspaceID+"/savedSearches/app-errors", func(r map[string]any) error {
		p := properties(r)
		tags, _ := p["tags"].([]any)
		if r["type"] != "Microsoft.OperationalInsights/workspaces/savedSearches" || p["category"] != "Application" ||
			p["displayName"] != "Application errors" || p["query"] != "AppEvents_CL | where Message contains 'error'" ||
			p["version"] != float64(2) || len(tags) != 1 {
			return fmt.Errorf("resource: %v", r)
		}
		return nil
	})
	expectResource(t, workspaceID+"/linkedStorageAccounts/CustomLogs", func(r map[string]any) error {
		ids, _ := properties(r)["storageAccountIds"].([]any)
		if r["type"] != "Microsoft.OperationalInsights/workspaces/linkedStorageAccounts" || !reflect.DeepEqual(ids, []any{storageID}) {
			return fmt.Errorf("resource: %v", r)
		}
		return nil
	})
	expectResource(t, workspaceID+"/linkedServices/Automation", func(r map[string]any) error {
		if r["type"] != "Microsoft.OperationalInsights/workspaces/linkedServices" || properties(r)["resourceId"] != automationID {
			return fmt.Errorf("resource: %v", r)
		}
		return nil
	})
	expectResource(t, workspaceID+"/dataExports/archive", func(r map[string]any) error {
		p := properties(r)
		dest, _ := p["destination"].(map[string]any)
		if r["type"] != "Microsoft.OperationalInsights/workspaces/dataExports" || p["enable"] != true ||
			!reflect.DeepEqual(p["tableNames"], []any{"Heartbeat", "AppEvents_CL"}) || dest["resourceId"] != storageID {
			return fmt.Errorf("resource: %v", r)
		}
		return nil
	})
	if refs := table.GetOwnerReferences(); len(refs) != 1 || refs[0].Name != "law" {
		t.Fatalf("owner references: %+v", refs)
	}

	// A change to the table is PUT again; a status read back from Azure fills
	// the Kubernetes object.
	if err := k8s.Get(ctx, client.ObjectKeyFromObject(table), table); err != nil {
		t.Fatal(err)
	}
	table.Spec.RetentionInDays = ptr(90)
	if err := k8s.Update(ctx, table); err != nil {
		t.Fatal(err)
	}
	expectResource(t, tableID, func(r map[string]any) error {
		if properties(r)["retentionInDays"] != float64(90) {
			return fmt.Errorf("resource: %v", r)
		}
		return nil
	})
	eventually(t, timeout, "table status", func() error {
		if err := k8s.Get(ctx, client.ObjectKeyFromObject(table), table); err != nil {
			return err
		}
		if table.Status.RetentionInDays == nil || *table.Status.RetentionInDays != 90 {
			return fmt.Errorf("status.retentionInDays: %v", table.Status.RetentionInDays)
		}
		return nil
	})

	// Deleting them deletes them in Resource Manager and leaves ASO's
	// workspace alone.
	for _, o := range all {
		if err := k8s.Delete(ctx, o); err != nil {
			t.Fatal(err)
		}
		eventually(t, timeout, fmt.Sprintf("%T gone", o), gone(o))
	}
	for _, id := range []string{tableID, workspaceID + "/savedSearches/app-errors", workspaceID + "/linkedStorageAccounts/CustomLogs", workspaceID + "/linkedServices/Automation", workspaceID + "/dataExports/archive"} {
		if armFake.HasResource(id) {
			t.Fatalf("%s is still in Resource Manager", id)
		}
	}
	if !armFake.HasResource(workspaceID) {
		t.Fatal("the workspace is gone from Resource Manager")
	}
}

// A query pack owned by the resource group, and a query owned by our pack, not
// by ASO: the query's ARM ID runs through the pack.
func TestQueryPackAndQuery(t *testing.T) {
	ctx := context.Background()
	ns := namespace(t, "law-pack")
	strictCredential(t, ns, clientA)
	trustNamespace(ns)
	_, rgID := logAnalytics(t, ns)

	pack := &oi.QueryPack{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: "ops"},
		Spec: oi.QueryPack_Spec{
			Owner:    &genruntime.KnownResourceReference{Name: "rg"},
			Location: ptr("westus"),
			Tags:     map[string]string{"team": "platform"},
		},
	}
	if err := k8s.Create(ctx, pack); err != nil {
		t.Fatal(err)
	}
	eventually(t, timeout, "QueryPack Ready", ready(pack))
	packID := rgID + "/providers/Microsoft.OperationalInsights/queryPacks/ops"
	expectResource(t, packID, func(r map[string]any) error {
		tags, _ := r["tags"].(map[string]any)
		if r["type"] != "Microsoft.OperationalInsights/queryPacks" || r["location"] != "westus" || tags["team"] != "platform" {
			return fmt.Errorf("resource: %v", r)
		}
		return nil
	})

	query := &oi.QueryPacksQuery{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: "slow-requests"},
		Spec: oi.QueryPacksQuery_Spec{
			AzureName:   "6a0f1e1c-2a53-4a4e-9c3f-4d0a4f1b8a01",
			Owner:       &genruntime.KnownResourceReference{Name: "ops"},
			DisplayName: ptr("Slow requests"),
			Body:        ptr("requests | where duration > 5s"),
			Related:     &oi.LogAnalyticsQueryPackQueryPropertiesRelated{Categories: []string{"applications"}},
		},
	}
	if err := k8s.Create(ctx, query); err != nil {
		t.Fatal(err)
	}
	eventually(t, timeout, "QueryPacksQuery Ready", ready(query))
	queryID := packID + "/queries/6a0f1e1c-2a53-4a4e-9c3f-4d0a4f1b8a01"
	expectResource(t, queryID, func(r map[string]any) error {
		p := properties(r)
		related, _ := p["related"].(map[string]any)
		if r["type"] != "Microsoft.OperationalInsights/queryPacks/queries" || p["displayName"] != "Slow requests" ||
			p["body"] != "requests | where duration > 5s" || !reflect.DeepEqual(related["categories"], []any{"applications"}) {
			return fmt.Errorf("resource: %v", r)
		}
		return nil
	})

	for _, o := range []client.Object{query, pack} {
		if err := k8s.Delete(ctx, o); err != nil {
			t.Fatal(err)
		}
		eventually(t, timeout, fmt.Sprintf("%T gone", o), gone(o))
	}
	if armFake.HasResource(packID) || armFake.HasResource(queryID) {
		t.Fatal("the pack or its query is still in Resource Manager")
	}
}

// The CRD refuses a table plan that does not exist and a retention outside
// Log Analytics' limits.
func TestWorkspaceChildrenValidation(t *testing.T) {
	ctx := context.Background()
	ns := namespace(t, "law-validation")
	owner := &genruntime.KnownResourceReference{Name: "law"}
	badPlan := &oi.WorkspacesTable{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: "bad-plan"},
		Spec:       oi.WorkspacesTable_Spec{AzureName: "Bad_CL", Owner: owner, Plan: ptr(oi.TablePlanEnum("Premium"))},
	}
	if err := k8s.Create(ctx, badPlan); err == nil || !contains(err.Error(), "Unsupported value") {
		t.Fatalf("want a refusal of the plan, got %v", err)
	}
	badRetention := &oi.WorkspacesTable{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: "bad-retention"},
		Spec:       oi.WorkspacesTable_Spec{AzureName: "Bad_CL", Owner: owner, RetentionInDays: ptr(1)},
	}
	if err := k8s.Create(ctx, badRetention); err == nil || !contains(err.Error(), "greater than or equal to 4") {
		t.Fatalf("want a refusal of the retention, got %v", err)
	}
}
